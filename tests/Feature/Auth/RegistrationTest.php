<?php

test('backend registration is unavailable', function () {
    $response = $this->post('/register', [
        'name' => 'Test User',
        'email' => 'test@example.com',
        'password' => 'password',
        'password_confirmation' => 'password',
    ]);

    $response->assertMethodNotAllowed();
    $this->assertGuest();
});
